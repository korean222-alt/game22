/* Service worker: an offline-capable app shell.

   The game is entirely static and has no backend, so every asset can be
   precached at install and served from cache afterwards. That is what lets it
   open on a phone with no signal, and what makes a second launch instant.

   Bump CACHE when the shell changes; the activate handler drops older caches.
   Generated by the build note in README — do not hand-edit ASSETS.

   The boss monsters in assets/ are deliberately NOT precached. They are about a
   megabyte between them, only one species appears per project, and the runtime
   handler below caches each on first use — so a first launch on mobile data
   stays small and the monster is instant every time after. */

