self.addEventListener('install', (e) => {
  e.waitUntil((async () => {
    const c = await caches.open(CACHE);
    // addAll rejects the whole install if any single request fails, which on a
    // flaky first load would leave no cache at all. Fetch individually instead.
    await Promise.all(ASSETS.map((u) => c.add(u).catch(() => {})));
    self.skipWaiting();
  })());
});

self.addEventListener('activate', (e) => {
  e.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)));
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== location.origin) return;

  // Navigations go to the network first so a deploy is picked up promptly, and
  // fall back to the cached shell when offline.
  if (req.mode === 'navigate') {
    e.respondWith((async () => {
      try {
        const fresh = await fetch(req);
        const c = await caches.open(CACHE);
        c.put('./index.html', fresh.clone());
        return fresh;
      } catch (err) {
        return (await caches.match('./index.html')) || Response.error();
      }
    })());
    return;
  }

  /* ── 코드는 네트워크가 먼저다 ──
     예전에는 여기도 캐시 우선이었다. 배포가 나가도 폰에 깔린 예전 .js 가
     그대로 돌고, 새 파일은 **다음 실행**에나 붙는다는 뜻이다. 소리를 넣은
     판을 올려도 그 폰에서는 며칠째 무음이었던 것이 정확히 이 자리다.

     그래서 소스와 스타일만 네트워크를 먼저 본다. 1.5초 안에 안 오면 캐시로
     되돌아가므로 지하철에서도 예전처럼 열린다 — 오프라인에서 여는 값은
     그대로 두고, "고쳤는데 안 고쳐졌다" 만 없앤다. 모델·아이콘 같은 큰
     파일은 내용이 안 바뀌므로 예전대로 캐시가 먼저다. */
  const isCode = /\.(js|css|mjs)$/.test(url.pathname) || url.pathname.endsWith('/index.html');
  if (isCode) {
    e.respondWith((async () => {
      const c = await caches.open(CACHE);
      try {
        const fresh = await Promise.race([
          fetch(req),
          new Promise((_, rej) => setTimeout(() => rej(new Error('slow')), 1500)),
        ]);
        if (fresh && fresh.ok) { c.put(req, fresh.clone()); return fresh; }
        throw new Error('bad');
      } catch (err) {
        return (await caches.match(req)) || fetch(req).catch(() => Response.error());
      }
    })());
    return;
  }

  // Everything else: cache first, then refresh the entry in the background so
  // the next launch has the newer file without ever blocking on the network.
  e.respondWith((async () => {
    const hit = await caches.match(req);
    const net = fetch(req).then((res) => {
      if (res && res.ok) caches.open(CACHE).then((c) => c.put(req, res.clone()));
      return res;
    }).catch(() => null);
    return hit || (await net) || Response.error();
  })());
});
